for (const [lang, values] of Object.entries(T)) {
  if (values.length !== KEYS.length) throw new Error(`translation arity mismatch: ${lang}`)
  const file = path.join(dir, `${lang}.ts`)
  if (!fs.existsSync(file)) throw new Error(`missing locale file: ${file}`)
  let src = fs.readFileSync(file, 'utf8')
  const missing = KEYS.filter((k) => !src.includes(`${k}:`))
  if (missing.length === 0) {
    console.log(`skip ${lang} (all keys present)`)
    continue
  }
  const close = src.lastIndexOf('}')
  if (close === -1) throw new Error(`no closing brace: ${file}`)
  const block = KEYS.map((k, i) => ({ k, i }))
    .filter(({ k }) => missing.includes(k))
    .map(({ k, i }) => `  ${k}: ${JSON.stringify(values[i])},`)
    .join('\n')
  src = src.slice(0, close) + block + '\n' + src.slice(close)
  fs.writeFileSync(file, src)
  const after = fs.readFileSync(file, 'utf8')
  for (const k of KEYS) {
    if (!after.includes(`${k}:`)) throw new Error(`insert failed for ${k} in ${lang}`)
  }
  console.log(`ok ${lang}`)
}
